CREATE TABLE parametros_sistema (
    clave         VARCHAR(100) PRIMARY KEY,
    descripcion   VARCHAR(255) NOT NULL,
    unidad        VARCHAR(50),
    valor         INTEGER      NOT NULL,
    valor_defecto INTEGER      NOT NULL,
    minimo        INTEGER      NOT NULL,
    maximo        INTEGER      NOT NULL
);


-- Esquema inicial de SistemaTicket en PostgreSQL.
-- Generado a partir de las entidades JPA; Adjunto.contenido es bytea (no oid).

-- ---------------------------------------------------------------- Tablas

CREATE TABLE usuarios_ticket (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre             VARCHAR(255) NOT NULL,
    apellido           VARCHAR(255) NOT NULL,
    correo_electronico VARCHAR(255) NOT NULL UNIQUE,
    telefono           VARCHAR(255),
    activo             BOOLEAN      NOT NULL,
    fecha_registro     TIMESTAMP(6) NOT NULL
);

CREATE TABLE operadores (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre             VARCHAR(255) NOT NULL,
    apellido           VARCHAR(255) NOT NULL,
    correo_electronico VARCHAR(255) NOT NULL UNIQUE,
    area               VARCHAR(255),
    cargo              VARCHAR(255),
    activo             BOOLEAN      NOT NULL
);

CREATE TABLE categorias (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(255) NOT NULL UNIQUE,
    descripcion VARCHAR(255),
    area        VARCHAR(255),
    activa      BOOLEAN      NOT NULL
);

CREATE TABLE prioridades (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nivel                    VARCHAR(255) NOT NULL UNIQUE
        CHECK (nivel IN ('BAJA', 'MEDIA', 'ALTA', 'CRITICA')),
    descripcion              VARCHAR(255),
    tiempo_objetivo_respuesta INTEGER
);

CREATE TABLE ticket_estados (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo             VARCHAR(255) NOT NULL UNIQUE
        CHECK (codigo IN ('NUEVO', 'PENDIENTE_CORRECCION', 'VALIDADO', 'EN_ANALISIS',
                          'RESUELTO', 'CERRADO', 'REABIERTO')),
    nombre             VARCHAR(255) NOT NULL,
    descripcion        VARCHAR(255),
    estado_final       BOOLEAN      NOT NULL,
    permite_reapertura BOOLEAN      NOT NULL
);

CREATE TABLE tickets (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo                     VARCHAR(150)  NOT NULL,
    descripcion                VARCHAR(2000) NOT NULL,
    usuario_id                 BIGINT        NOT NULL,
    categoria_id               BIGINT,
    prioridad_id               BIGINT,
    prioridad_sugerida_id      BIGINT,
    operador_id                BIGINT,
    estado_actual_id           BIGINT        NOT NULL,
    validado                   BOOLEAN       NOT NULL,
    resolucion                 VARCHAR(2000),
    motivo_cierre              VARCHAR(2000),
    motivo_reapertura          VARCHAR(2000),
    fecha_creacion             TIMESTAMP(6)  NOT NULL,
    fecha_ultima_actualizacion TIMESTAMP(6),
    fecha_cierre               TIMESTAMP(6),
    CONSTRAINT fk_tickets_usuario            FOREIGN KEY (usuario_id)            REFERENCES usuarios_ticket,
    CONSTRAINT fk_tickets_categoria          FOREIGN KEY (categoria_id)          REFERENCES categorias,
    CONSTRAINT fk_tickets_prioridad          FOREIGN KEY (prioridad_id)          REFERENCES prioridades,
    CONSTRAINT fk_tickets_prioridad_sugerida FOREIGN KEY (prioridad_sugerida_id) REFERENCES prioridades,
    CONSTRAINT fk_tickets_operador           FOREIGN KEY (operador_id)           REFERENCES operadores,
    CONSTRAINT fk_tickets_estado_actual      FOREIGN KEY (estado_actual_id)      REFERENCES ticket_estados
);

CREATE TABLE adjuntos (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id         BIGINT       NOT NULL,
    nombre_archivo    VARCHAR(255) NOT NULL,
    tipo_archivo      VARCHAR(255) NOT NULL,
    tamano            BIGINT       NOT NULL,
    fecha_carga       TIMESTAMP(6) NOT NULL,
    descripcion       VARCHAR(255),
    contenido         BYTEA        NOT NULL,
    operador_autor_id BIGINT,
    CONSTRAINT fk_adjuntos_ticket         FOREIGN KEY (ticket_id)         REFERENCES tickets,
    CONSTRAINT fk_adjuntos_operador_autor FOREIGN KEY (operador_autor_id) REFERENCES operadores
);

CREATE TABLE comentarios (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id         BIGINT        NOT NULL,
    contenido         VARCHAR(2000) NOT NULL,
    es_interno        BOOLEAN       NOT NULL,
    fecha_creacion    TIMESTAMP(6)  NOT NULL,
    operador_autor_id BIGINT,
    usuario_autor_id  BIGINT,
    CONSTRAINT fk_comentarios_ticket         FOREIGN KEY (ticket_id)         REFERENCES tickets,
    CONSTRAINT fk_comentarios_operador_autor FOREIGN KEY (operador_autor_id) REFERENCES operadores,
    CONSTRAINT fk_comentarios_usuario_autor  FOREIGN KEY (usuario_autor_id)  REFERENCES usuarios_ticket
);

CREATE TABLE historial_estados (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id        BIGINT       NOT NULL,
    ticket_estado_id BIGINT       NOT NULL,
    tipo             VARCHAR(255)
        CHECK (tipo IN ('CAMBIO_ESTADO', 'ACTUALIZACION', 'ACCION')),
    fecha_cambio     TIMESTAMP(6) NOT NULL,
    motivo_cambio    VARCHAR(2000),
    observacion      VARCHAR(2000),
    actor_operador_id BIGINT,
    actor_usuario_id  BIGINT,
    CONSTRAINT fk_historial_estados_ticket          FOREIGN KEY (ticket_id)         REFERENCES tickets,
    CONSTRAINT fk_historial_estados_estado          FOREIGN KEY (ticket_estado_id)  REFERENCES ticket_estados,
    CONSTRAINT fk_historial_estados_actor_operador  FOREIGN KEY (actor_operador_id) REFERENCES operadores,
    CONSTRAINT fk_historial_estados_actor_usuario   FOREIGN KEY (actor_usuario_id)  REFERENCES usuarios_ticket
);

CREATE TABLE historial_asignaciones (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id                BIGINT       NOT NULL,
    tipo_accion              VARCHAR(255) NOT NULL
        CHECK (tipo_accion IN ('ASIGNACION', 'REASIGNACION')),
    fecha_asignacion         TIMESTAMP(6) NOT NULL,
    motivo                   VARCHAR(255),
    operador_anterior_id     BIGINT,
    operador_nuevo_id        BIGINT       NOT NULL,
    operador_responsable_id  BIGINT       NOT NULL,
    CONSTRAINT fk_hist_asignaciones_ticket      FOREIGN KEY (ticket_id)               REFERENCES tickets,
    CONSTRAINT fk_hist_asignaciones_anterior    FOREIGN KEY (operador_anterior_id)    REFERENCES operadores,
    CONSTRAINT fk_hist_asignaciones_nuevo       FOREIGN KEY (operador_nuevo_id)       REFERENCES operadores,
    CONSTRAINT fk_hist_asignaciones_responsable FOREIGN KEY (operador_responsable_id) REFERENCES operadores
);

CREATE TABLE notificaciones (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mensaje                  VARCHAR(500) NOT NULL,
    tipo_canal               VARCHAR(255) NOT NULL,
    estado_envio             VARCHAR(255) NOT NULL
        CHECK (estado_envio IN ('PENDIENTE', 'ENVIADA', 'FALLIDA', 'LEIDA')),
    intentos                 INTEGER,
    fecha_envio              TIMESTAMP(6) NOT NULL,
    fecha_lectura            TIMESTAMP(6),
    ticket_id                BIGINT,
    historial_estado_id      BIGINT,
    destinatario_operador_id BIGINT,
    destinatario_usuario_id  BIGINT,
    CONSTRAINT fk_notificaciones_ticket             FOREIGN KEY (ticket_id)                REFERENCES tickets,
    CONSTRAINT fk_notificaciones_historial_estado   FOREIGN KEY (historial_estado_id)      REFERENCES historial_estados,
    CONSTRAINT fk_notificaciones_dest_operador      FOREIGN KEY (destinatario_operador_id) REFERENCES operadores,
    CONSTRAINT fk_notificaciones_dest_usuario       FOREIGN KEY (destinatario_usuario_id)  REFERENCES usuarios_ticket
);

-- Permisos: herencia SINGLE_TABLE (Permiso / GrupoPermisos) con discriminador "tipo".
CREATE TABLE componentes_permiso (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo        VARCHAR(31)  NOT NULL,
    codigo      VARCHAR(255) NOT NULL UNIQUE,
    descripcion VARCHAR(255)
);

CREATE TABLE grupo_hijos (
    grupo_id BIGINT NOT NULL,
    hijo_id  BIGINT NOT NULL,
    CONSTRAINT fk_grupo_hijos_grupo FOREIGN KEY (grupo_id) REFERENCES componentes_permiso,
    CONSTRAINT fk_grupo_hijos_hijo  FOREIGN KEY (hijo_id)  REFERENCES componentes_permiso
);

CREATE TABLE cuentas_acceso (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_login         VARCHAR(255) NOT NULL UNIQUE,
    password_hash         VARCHAR(255) NOT NULL,
    rol                   VARCHAR(255) NOT NULL
        CHECK (rol IN ('USUARIO', 'OPERADOR', 'ADMINISTRADOR')),
    activa                BOOLEAN      NOT NULL,
    debe_cambiar_password BOOLEAN      NOT NULL,
    intentos_fallidos     INTEGER      NOT NULL,
    bloqueada_hasta       TIMESTAMP(6),
    fecha_ultimo_acceso   TIMESTAMP(6),
    operador_id           BIGINT UNIQUE,
    usuario_ticket_id     BIGINT UNIQUE,
    CONSTRAINT fk_cuentas_acceso_operador FOREIGN KEY (operador_id)       REFERENCES operadores,
    CONSTRAINT fk_cuentas_acceso_usuario  FOREIGN KEY (usuario_ticket_id) REFERENCES usuarios_ticket
);

CREATE TABLE cuenta_componentes (
    cuenta_id     BIGINT NOT NULL,
    componente_id BIGINT NOT NULL,
    CONSTRAINT fk_cuenta_componentes_cuenta     FOREIGN KEY (cuenta_id)     REFERENCES cuentas_acceso,
    CONSTRAINT fk_cuenta_componentes_componente FOREIGN KEY (componente_id) REFERENCES componentes_permiso
);
